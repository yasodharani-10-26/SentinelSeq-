import express, { Request, Response } from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json());

// Initialize Gemini client if API key is present
const geminiApiKey = process.env.GEMINI_API_KEY;
let ai: GoogleGenAI | null = null;

if (geminiApiKey) {
  ai = new GoogleGenAI({
    apiKey: geminiApiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

// Health check endpoint
app.get('/api/health', (_req: Request, res: Response) => {
  res.json({
    status: 'online',
    timestamp: new Date().toISOString(),
    geminiEnabled: Boolean(geminiApiKey),
  });
});

// AI SOC Forensic Advisor Endpoint
app.post('/api/gemini/forensic-advisor', async (req: Request, res: Response) => {
  const {
    currentBehavior,
    predictedNextStage,
    confidence,
    anomalyScore,
    sequenceHistory,
    trafficFeatures,
    datasetSource,
    mitreTechniques,
  } = req.body;

  if (!ai) {
    // Graceful structured response when API key is unconfigured
    return res.json({
      status: 'simulated',
      attribution: {
        threatActorProfile: 'Automated Opportunistic Scanner / Advanced Threat Group',
        mitreTactic: 'Initial Access & Execution Anticipation',
        cveVulnerabilities: ['CVE-2017-5638 (Apache Struts)', 'CVE-2014-0160 (Heartbleed)', 'CVE-2017-0144 (EternalBlue)'],
      },
      forensicRationale: `The network behavior sequence transitioned from ${sequenceHistory?.map((s: { stage: string }) => s.stage).join(' → ') || currentBehavior} to ${currentBehavior}. The high volume of SYN packets, compressed inter-arrival window, and elevated port entropy strongly indicate weaponized reconnaissance preparing for immediate exploit payload delivery.`,
      recommendedContainment: [
        'Apply immediate rate-limiting on target subnet for ingress TCP packets with SYN flag only.',
        'Isolate vulnerable external endpoints exposing ports identified in the scan window.',
        'Deploy honeypot redirect on non-essential listening ports to capture the active payload signature.',
        'Capture full-packet PCAP buffer for forensic hash generation prior to automated drop.',
      ],
      generatedFirewallRule: `# Proactive SOC Defense Rule (Generated for ${currentBehavior} -> ${predictedNextStage})\niptables -A INPUT -p tcp --syn -m limit --limit 50/s --limit-burst 100 -j ACCEPT\niptables -A INPUT -p tcp --tcp-flags SYN,ACK,FIN,RST SYN -m recent --name SCAN_TEMP --set\niptables -A INPUT -p tcp --tcp-flags SYN,ACK,FIN,RST SYN -m recent --name SCAN_TEMP --update --seconds 60 --hitcount 25 -j DROP`,
    });
  }

  try {
    const prompt = `You are a Principal Cyber Defense Architect and Temporal AI Threat Analyst.
Analyze the following live attack sequence forecast generated by our Temporal AI World Model trained on datasets (${datasetSource || 'CIC-IDS2017 / UNSW-NB15'}):

[CURRENT SITUATION]
- Observed Sequence: ${JSON.stringify(sequenceHistory || [])}
- Current Network Behavior: ${currentBehavior}
- Predicted Next Attack Stage: ${predictedNextStage}
- Temporal Forecast Confidence: ${confidence}%
- Anomaly / Novelty Score: ${anomalyScore}%
- Key Traffic Metrics:
  * Packet Count: ${trafficFeatures?.packetCount ?? 'N/A'}
  * Connection Rate: ${trafficFeatures?.connectionRate ?? 'N/A'} conn/sec
  * SYN Flag Ratio: ${trafficFeatures?.synRatio ?? 'N/A'}%
  * Flow Duration: ${trafficFeatures?.flowDuration ?? 'N/A'} ms
  * Target Port Entropy: ${trafficFeatures?.portEntropy ?? 'N/A'}
  * Protocols: ${trafficFeatures?.protocols ?? 'TCP / HTTP / SMB'}
- Correlated MITRE ATT&CK: ${JSON.stringify(mitreTechniques || [])}

Provide an actionable, technical SOC forensic advisory in JSON format:
{
  "attribution": {
    "threatActorProfile": "Detailed profile of probable threat actor / tooling (e.g., Mirai botnet, Cobalt Strike stager, Masscan/Nmap automated scanner, APT operator)",
    "mitreTactic": "Primary MITRE ATT&CK tactic in progression",
    "cveVulnerabilities": ["List of 2-4 known CVEs matching this sequence pattern in benchmark datasets"]
  },
  "forensicRationale": "Concise 2-3 sentence technical explanation of why the temporal pattern signals this specific next attack progression, explaining how the network feature shifts act as early indicators.",
  "recommendedContainment": [
    "3-4 prioritized proactive countermeasures the security analyst should review before the predicted stage executes"
  ],
  "generatedFirewallRule": "A clean, valid iptables or nftables CLI command to neutralize the incoming vector immediately"
}
Ensure the output is valid JSON matching this schema exactly.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        responseMimeType: 'application/json',
      },
    });

    const parsed = JSON.parse(response.text || '{}');
    return res.json({
      status: 'live_ai',
      ...parsed,
    });
  } catch (err: unknown) {
    console.error('Gemini forensic advisor error:', err);
    return res.status(500).json({
      error: 'Failed to generate AI forensic advisory',
      message: err instanceof Error ? err.message : String(err),
    });
  }
});

// Setup Vite middleware in dev or static files in production
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req: Request, res: Response) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`SentinelSeq Attack Forecasting server running on port ${PORT}`);
  });
}

startServer();
